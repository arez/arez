#!/usr/bin/env python3
"""Copy Arez's required root-module configuration into a downstream workspace."""

import argparse
import ast
import shutil
from pathlib import Path


def write_config(destination: Path) -> Path:
    workspace = Path(__file__).resolve().parent.parent
    source = (workspace / "MODULE.bazel").read_text().split(
        "# --- depgen-generated repository rules start ---", 1)[0]
    statements = []
    for statement in ast.parse(source).body:
        if isinstance(statement, ast.Expr) and isinstance(statement.value, ast.Call):
            call = statement.value
            if isinstance(call.func, ast.Name) and call.func.id == "module":
                continue
            if any(keyword.arg == "dev_dependency" and isinstance(keyword.value, ast.Constant)
                   and keyword.value.value is True for keyword in call.keywords):
                continue
            if isinstance(call.func, ast.Name) and call.func.id == "single_version_override" and any(
                keyword.arg == "module_name" and isinstance(keyword.value, ast.Constant)
                and keyword.value.value == "rules_webtesting" for keyword in call.keywords
            ):
                continue
        statements.append(ast.get_source_segment(source, statement))
    text = "\n\n".join(statements)
    text = text.replace('"//third_party/bazel/patches:', '"//third_party/arez/patches:')
    text = text.replace('"//:maven_install.json"', '"//third_party/arez:maven_install.json"')
    text = text.replace('known_contributing_modules = [', 'known_contributing_modules = [\n        "arez",')
    target = destination / "third_party/arez"
    target.mkdir(parents=True, exist_ok=True)
    shutil.copytree(workspace / "third_party/bazel/patches", target / "patches", dirs_exist_ok=True)
    shutil.copyfile(workspace / "maven_install.json", target / "maven_install.json")
    (target / "BUILD.bazel").write_text('exports_files(["maven_install.json"])\n')
    fragment = target / "dependencies.MODULE.bazel"
    fragment.write_text("# Generated by Arez tools/bazel_consumer_config.py; regenerate when updating Arez.\n\n" + text + "\n")
    return fragment


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("workspace", type=Path, help="downstream workspace root")
    args = parser.parse_args()
    print(write_config(args.workspace.resolve()))
